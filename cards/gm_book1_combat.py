A1, A2, A3, R = "◆", "◆◆", "◆◆◆", "⤾"
SAVE_STEPS = "Fort save each interval: crit success −2 stages, success −1, failure +1, crit failure +2."


def creature(slug, title, level, footer, stats, lines, back, cite, subtitle=None):
    ac, hp, fort, ref, will, per = stats
    return dict(tab="combat", kind="creature", slug=slug, title=title, subtitle=subtitle or f"Creature {level}".replace("-", "−"),
                footer=footer, stats=[("AC", ac), ("HP", hp), ("Fort", fort), ("Ref", ref), ("Will", will), ("Per", per)],
                lines=lines, back=back, cite=cite)


def affliction(slug, title, subtitle, stages, lines, back, cite, footer):
    return dict(tab="combat", kind="affliction", slug=slug, title=title, subtitle=subtitle, stages=stages,
                lines=lines, back=back, cite=cite, footer=footer)


